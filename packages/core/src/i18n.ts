export const catalogs = { en, sv, ar }
export type MessageId = keyof typeof en
export function resolveLocale(locale = 'en'): keyof typeof catalogs {
  const language = locale.toLowerCase().split('-')[0]
  return language in catalogs ? (language as keyof typeof catalogs) : 'en'
}
export function translator(locale?: string, overrides: Record<string, string> = {}) {
  const catalog = catalogs[resolveLocale(locale)]
  return (id: string) => overrides[id] ?? catalog[id as MessageId] ?? en[id as MessageId] ?? id
}
